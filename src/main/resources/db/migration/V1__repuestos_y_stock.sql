-- =====================================================================
-- V1 de ms-catalog: repuestos con stock e historial de movimientos
-- =====================================================================
-- ms-catalog es el único dueño del stock. ms-workorders referencia el repuesto
-- por ID (DETALLE_OT_REPUESTO.ID_REPUESTO, sin FK porque vive en otro servicio)
-- y pide salidas/devoluciones por la API /api/catalog/stock.
--
-- Regla del caso: el stock del repuesto disminuye al asignar la orden. Cada
-- cambio deja una fila en MOVIMIENTO_STOCK (ENTRADA, SALIDA o DEVOLUCION).

-- Oracle Autonomous ejecuta DML en paralelo por defecto; se desactiva para que
-- los INSERT de movimientos puedan leer REPUESTO en la misma transacción.
ALTER SESSION DISABLE PARALLEL DML;

CREATE TABLE REPUESTO (
    ID_REPUESTO         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CODIGO              VARCHAR2(30)  NOT NULL,
    NOMBRE              VARCHAR2(100) NOT NULL,
    DESCRIPCION         VARCHAR2(255),
    UNIDAD_MEDIDA       VARCHAR2(20)  NOT NULL,
    PRECIO_UNITARIO     NUMBER(12,2)  NOT NULL,
    STOCK_DISPONIBLE    NUMBER(10)    NOT NULL,
    STOCK_MINIMO        NUMBER(10)    NOT NULL,
    ACTIVO              NUMBER(1)     DEFAULT 1 NOT NULL,
    FECHA_CREACION      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    VERSION             NUMBER(19)    DEFAULT 0 NOT NULL,
    CONSTRAINT PK_REPUESTO PRIMARY KEY (ID_REPUESTO),
    CONSTRAINT UK_REPUESTO_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_REPUESTO_STOCK CHECK (STOCK_DISPONIBLE >= 0),
    CONSTRAINT CK_REPUESTO_STOCK_MIN CHECK (STOCK_MINIMO >= 0),
    CONSTRAINT CK_REPUESTO_PRECIO CHECK (PRECIO_UNITARIO >= 0),
    CONSTRAINT CK_REPUESTO_UNIDAD CHECK (UNIDAD_MEDIDA IN ('UNIDAD', 'METRO', 'ROLLO', 'CAJA', 'KIT')),
    CONSTRAINT CK_REPUESTO_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE TABLE MOVIMIENTO_STOCK (
    ID_MOVIMIENTO    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ID_REPUESTO      NUMBER(19)   NOT NULL,
    TIPO             VARCHAR2(20) NOT NULL,
    CANTIDAD         NUMBER(10)   NOT NULL,
    STOCK_RESULTANTE NUMBER(10)   NOT NULL,
    REFERENCIA       VARCHAR2(60) NOT NULL,
    USUARIO          VARCHAR2(150),
    FECHA_MOVIMIENTO TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MOVIMIENTO_STOCK PRIMARY KEY (ID_MOVIMIENTO),
    CONSTRAINT FK_MOV_STOCK_REPUESTO FOREIGN KEY (ID_REPUESTO) REFERENCES REPUESTO (ID_REPUESTO),
    CONSTRAINT CK_MOV_STOCK_TIPO CHECK (TIPO IN ('ENTRADA', 'SALIDA', 'DEVOLUCION')),
    CONSTRAINT CK_MOV_STOCK_CANTIDAD CHECK (CANTIDAD > 0)
);

CREATE INDEX IDX_MOV_STOCK_REPUESTO ON MOVIMIENTO_STOCK (ID_REPUESTO);
CREATE INDEX IDX_MOV_STOCK_REFERENCIA ON MOVIMIENTO_STOCK (REFERENCIA);

-- Correlativo de CODIGO (REP-0001...). Va después de las tablas: Oracle no revierte DDL,
-- así que si REPUESTO ya existiera la migración falla antes de crear nada.
CREATE SEQUENCE SEQ_CODIGO_REPUESTO START WITH 1 INCREMENT BY 1 NOCACHE;

